void cx4e04_pll_status(void)
{
    u32 pll1_status;
    u32 lopll_status;
    u32 lopll_aac;
    pll1_status = cx4e04_read(CX4E04_PLL1_INPUT_CLOCK_STATE_REG) ;
    lopll_status = cx4e04_read(CX4E04_LOPLL_LOCK_STATE_REG) ;
    lopll_aac = cx4e04_read(CX4E04_LOPLL_AAC_READY_REG) ;

    fmsh_print("pll1_status:0x%x \r\nlopll_status:0x%x\r\nlopll_aac:0x%x\r\n",pll1_status,lopll_status,lopll_aac);
    fmsh_print("input pll_status:0x%x = %-10s\r\n", pll1_status, (((pll1_status>>4) & 0x01 ) ) ?"LOCK":"UNLOCK");
    fmsh_print("input pll_channel0: %-10s\r\n",((pll1_status>>0) & 0x01) ?"LOS":"Active");
    fmsh_print("input pll_channel1: %-10s\r\n",((pll1_status>>1) & 0x01) ?"LOS":"Active");
    fmsh_print("input pll_channel2: %-10s\r\n",((pll1_status>>2) & 0x01) ?"LOS":"Active");
    fmsh_print("input pll_channel3: %-10s\r\n",((pll1_status>>3) & 0x01) ?"LOS":"Active");
    fmsh_print("LOPLL = %-10s\r\n", (((lopll_status>>0) & 0x01 ) & ((lopll_status>>1) & 0x01 )) ?"LOCK":"UNLOCK");
    fmsh_print("AAC = %-10s\r\n",((lopll_aac>>2) & 0x01 )?"ready":"no ready");
}

void cx4e04_rst()
{
  FGpioPs_T gpio0;
  FGpioPs_bank_init(FPAR_GPIOPS_0_DEVICE_ID, &gpio0);  /*gpio bank0, mio 0-25*/
  FGpioPs_setBitDirection(&gpio0, Gpio_bit_8, Gpio_output);
  FGpioPs_writeBit(&gpio0, Gpio_low, Gpio_bit_8);
  delay_ms(500);
  FGpioPs_writeBit(&gpio0, Gpio_high, Gpio_bit_8);
  fmsh_print("cx4e04 rst\r\n");
}

void cx4e04_init()
{
    fmsh_print("cx4e04 init\r\n");
    cx4e04_rst();
    spi_config_init(&spi0, CX4E04_SPI_DEV);
    cx4e04_config();
    delay_ms(300);
    cx4e04_pll_status();    
}