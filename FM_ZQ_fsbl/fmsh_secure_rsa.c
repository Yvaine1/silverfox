u32 UtilPollForValue (u32 RegAddress, u32 Mask, u32 time_us, u32 Value)
{
    u32 reg = 0U;
    u32 TimeOutCount = time_us;

    reg = ReadReg(RegAddress);
    reg ^= Value;            // identify bits that not match with Value
    if ((reg & Mask) == 0U)  // Mask: 0 = don't care
    {
        return FMSH_SUCCESS;
    }

    while (1)
    {
        reg = ReadReg(RegAddress);
        reg ^= Value;            // identify bits that not match with Value
        if ((reg & Mask) == 0U)  // Mask: 0 = don't care
        {
            break;
        }
        delay_1us();
        TimeOutCount--;
        if (TimeOutCount == 0U)
        {
            return FMSH_FAILURE;
        }
    }
    return FMSH_SUCCESS;
}

/*****************************************************************************/
/**
 * @brief
 * This function initializes a specific FSecureRsa_Config_T instance so that it
 * is ready to be used.
 *
 * @param InstancePtr    Pointer to the FSecureRsa_Config_T instance.
 * @param Mod    A character Pointer which contains the key Modulus of key size.
 * @param ModExpo    Pointer to the buffer which contains key exponent.
 *
 * @return FMSH_SUCCESS if initialization was successful
 *
 * @note     'Modulus' and 'ModExpo' are part of patition signature when
 *       authenticated boot image is generated by bootgen, else the all
 *       of them should be extracted from the key.
 ******************************************************************************/
s32 FSecure_RsaInitialize (FSecureRsa_Config_T *InstancePtr, u32 *Mod,
                           u32 *ModExpo)
{
    /* Assert validates the input arguments */
    FMSH_ASSERT(InstancePtr != NULL);
    FMSH_ASSERT(Mod != NULL);
    FMSH_ASSERT(ModExpo != NULL);

    InstancePtr->BaseAddress = RSA_ENGINE_REG_BASE_ADDR;
    InstancePtr->Mod = Mod;
    InstancePtr->ModExpo = ModExpo;
    InstancePtr->SizeInWords = FSECURE_RSA_4096_SIZE_WORDS;
    InstancePtr->Endianness = RSA_LITTLE_ENDIAN_FORMAT;

    return FMSH_SUCCESS;
}

/*****************************************************************************/
/**
 * @brief
 * This function writes data to RSA RAM at a given offset
 *
 * @param InstancePtr    Pointer to the FSecureRsa_Config_T instance
 * @param WrData         Pointer to the data to be written to RSA RAM
 * @param RamOffset      Offset for the data to be written in RSA RAM
 *
 * @return None
 *
 * @note   None
 *
 ******************************************************************************/
static void FSecure_RsaWriteMem (FSecureRsa_Config_T *InstancePtr, u32 *WrData,
                                 u32 RamOffset)
{
    /* Assert validates the input arguments */
    FMSH_ASSERT(InstancePtr != NULL);

    u32 DataOffset = 0U;
    u32 Data = 0U;
    u32 Offset_Length = InstancePtr->SizeInWords;
    u32 RegisterValue;
    for (DataOffset = 0U; DataOffset < Offset_Length; DataOffset++)
    {
        // Data = WrData[(InstancePtr->SizeInWords - 1) - DataOffset];
        Data = WrData[DataOffset];
        if (InstancePtr->Endianness == RSA_LITTLE_ENDIAN_FORMAT)
        {
            RegisterValue = Data;
        }
        else
        {
            RegisterValue = FEndianSwap32(
                Data); /* In Big Endian, data should be reversed.*/
        }
        FSecure_WriteReg(InstancePtr->BaseAddress, RamOffset + (DataOffset * 4),
                         RegisterValue);
    }
}

/*****************************************************************************/
/**
 * @brief
 * This function writes all the RSA data used for decryption(Modulus, Exponent)
 * at the corresponding offsets in RSA RAM.
 *
 * @param    InstancePtr     Pointer to the FSecureRsa_Config_T instance.
 *
 * @return   None.
 *
 *
 ******************************************************************************/
static void FSecure_RsaPutData (FSecureRsa_Config_T *InstancePtr)
{
    /* Assert validates the input arguments */
    FMSH_ASSERT(InstancePtr != NULL);

    for (u32 DataOffset = 0; DataOffset < InstancePtr->SizeInWords;
         DataOffset++)
    {
        FSecure_WriteReg(InstancePtr->BaseAddress,
                         FSECURE_CSU_RSA_RAM_EXPO + (DataOffset * 4), 0x0);
    }
    u32 *WrData;
    WrData = (u32 *)InstancePtr->ModExpo;
    FSecure_WriteReg(InstancePtr->BaseAddress, FSECURE_CSU_RSA_RAM_EXPO,
                     WrData[0]);
    /* Initialize Modular exponentiation */
    // FSecure_RsaWriteMem(InstancePtr, (u32 *)InstancePtr->ModExpo,
    //                     FSECURE_CSU_RSA_RAM_EXPO);

    /* Initialize Modular. */
    FSecure_RsaWriteMem(InstancePtr, (u32 *)InstancePtr->Mod,
                        FSECURE_CSU_RSA_RAM_MOD);
}

/*****************************************************************************/
/**
 * @brief
 * This function reads back the resulting data from RSA RAM.
 *
 * @param    InstancePtr Pointer to the FSecureRsa_Config_T instance.
 * @param    RdData      Pointer to location where the decrypted data will
 *       be written.
 *
 * @return   None
 *
 *
 ******************************************************************************/
static void FSecure_RsaGetData (FSecureRsa_Config_T *InstancePtr, u32 *RdData)
{
    /* Assert validates the input arguments */
    FMSH_ASSERT(InstancePtr != NULL);

    u32 TmpSizeInWords = 0U;
    u32 TmpIndex = 0U;
    u32 TmpData = 0U;
    TmpSizeInWords = InstancePtr->SizeInWords;

    for (TmpIndex = 0U; TmpIndex < TmpSizeInWords; TmpIndex++)
    {
        TmpData = FSecure_ReadReg(InstancePtr->BaseAddress,
                                  FSECURE_CSU_RSA_RAM_RES + (TmpIndex * 4));
        if (InstancePtr->Endianness == RSA_LITTLE_ENDIAN_FORMAT)
        {
            // TmpData = TmpData;
            TmpData = FEndianSwap32(TmpData);
        }
        else
        {
            TmpData = FEndianSwap32(
                TmpData); /* In Big Endian, data should be reversed.*/
        }
        RdData[TmpSizeInWords - TmpIndex - 1] = TmpData;
    }
}

/*****************************************************************************/
/**
 * @brief
 * This function handles the RSA signature encryption with public key components
 * provide at FSecure_RsaInitialize() API.
 *
 * @param    InstancePtr Pointer to the FSecureRsa_Config_T instance.
 * @param    Input       Pointer to the buffer which contains the input
 *       data to be decrypted.
 * @param    Size        Key size in bytes, Input size also should be same as
 *       Key size mentioned. Inputs supported are
 *       - FSECURE_RSA_4096_SIZE_WORDS and
 *       - FSECURE_RSA_2048_SIZE_WORDS
 * @param    Result      Pointer to the buffer where resultant decrypted
 *       data to be stored.
 *
 * @return   FMSH_SUCCESS if encryption was successful.
 *
 * @note     Modulus of API FSecure_RsaInitialize() should also be same size
 *        of key size mentioned in this API and exponent should be 32 bit size.
 *
 ******************************************************************************/
s32 FSecure_RsaPublicEncrypt (FSecureRsa_Config_T *InstancePtr, u32 *Input,
                              u32 Size, u32 *Result)
{
    s32 ErrorCode = FMSH_SUCCESS;

    /* Assert validates the input arguments */
    FMSH_ASSERT(InstancePtr != NULL);
    FMSH_ASSERT(Result != NULL);
    FMSH_ASSERT(Input != NULL);
    FMSH_ASSERT((Size == FSECURE_RSA_512_SIZE_WORDS) ||
                (Size == FSECURE_RSA_1024_SIZE_WORDS) ||
                (Size == FSECURE_RSA_2048_SIZE_WORDS) ||
                (Size == FSECURE_RSA_4096_SIZE_WORDS));

    /* Setting for RSA signature encryption with public key */
    InstancePtr->EncDec = FSECURE_ENC;
    InstancePtr->SizeInWords = Size;

    ErrorCode = FSecure_RsaOperation(InstancePtr, Input, Result);

    return ErrorCode;
}

